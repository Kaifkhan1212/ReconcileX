CREATE TABLE file_imports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_type VARCHAR(30) NOT NULL
        CHECK (file_type IN (
            'BANK_STATEMENT',
            'INTERNAL_TRANSACTIONS'
        )),
    file_name VARCHAR(255) NOT NULL,
    file_sha256 VARCHAR(64) NOT NULL
        CHECK (LENGTH(file_sha256) = 64),
    status VARCHAR(30) NOT NULL
        CHECK (status IN (
            'PENDING',
            'IN_PROGRESS',
            'COMPLETED',
            'COMPLETED_WITH_ERRORS',
            'FAILED'
        )),
    total_rows INTEGER NOT NULL DEFAULT 0 CHECK (total_rows >= 0),
    imported_rows INTEGER NOT NULL DEFAULT 0 CHECK (imported_rows >= 0),
    rejected_rows INTEGER NOT NULL DEFAULT 0 CHECK (rejected_rows >= 0),
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    CONSTRAINT uq_file_import_type_hash UNIQUE (file_type, file_sha256)
);

CREATE TABLE bank_statement_rows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_import_id BIGINT NOT NULL
        REFERENCES file_imports(id) ON DELETE RESTRICT,
    source_row_number INTEGER NOT NULL CHECK (source_row_number > 0),
    transaction_date DATE NOT NULL,
    bank_reference VARCHAR(120),
    payment_reference VARCHAR(120),
    settlement_reference VARCHAR(120),
    description TEXT,
    credit_amount NUMERIC(19, 2) NOT NULL DEFAULT 0 CHECK (credit_amount >= 0),
    debit_amount NUMERIC(19, 2) NOT NULL DEFAULT 0 CHECK (debit_amount >= 0),
    currency VARCHAR(3) NOT NULL,
    CONSTRAINT uq_bank_statement_import_row
        UNIQUE (file_import_id, source_row_number),
    CONSTRAINT uq_bank_statement_bank_ref
        UNIQUE (bank_reference)
);

CREATE INDEX idx_bank_rows_payment_reference
    ON bank_statement_rows(payment_reference);

CREATE INDEX idx_bank_rows_settlement_reference
    ON bank_statement_rows(settlement_reference);

CREATE INDEX idx_bank_rows_transaction_date
    ON bank_statement_rows(transaction_date);

CREATE TABLE internal_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_import_id BIGINT NOT NULL
        REFERENCES file_imports(id) ON DELETE RESTRICT,
    source_row_number INTEGER NOT NULL CHECK (source_row_number > 0),
    transaction_id VARCHAR(100) NOT NULL,
    payment_reference VARCHAR(120),
    transaction_date DATE NOT NULL,
    description TEXT,
    amount NUMERIC(19, 2) NOT NULL CHECK (amount >= 0),
    currency VARCHAR(3) NOT NULL,
    payment_status VARCHAR(40) NOT NULL
        CHECK (payment_status IN (
            'SUCCESS',
            'PENDING',
            'FAILED',
            'REFUNDED',
            'REFUND_INITIATED'
        )),
    settlement_reference VARCHAR(120),
    CONSTRAINT uq_internal_import_row
        UNIQUE (file_import_id, source_row_number),
    CONSTRAINT uq_internal_transactions_txn_id
        UNIQUE (transaction_id)
);

CREATE INDEX idx_internal_payment_reference
    ON internal_transactions(payment_reference);

CREATE INDEX idx_internal_settlement_reference
    ON internal_transactions(settlement_reference);

CREATE INDEX idx_internal_transaction_date
    ON internal_transactions(transaction_date);

CREATE TABLE reconciliation_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_import_id BIGINT NOT NULL
        REFERENCES file_imports(id) ON DELETE RESTRICT,
    internal_import_id BIGINT NOT NULL
        REFERENCES file_imports(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED')),
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ
);

CREATE INDEX idx_reconciliation_runs_status
    ON reconciliation_runs(status);

CREATE TABLE reconciliation_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL
        REFERENCES reconciliation_runs(id) ON DELETE CASCADE,
    result_type VARCHAR(40) NOT NULL
        CHECK (result_type IN (
            'EXACT_MATCH',
            'AMOUNT_MISMATCH',
            'DATE_MISMATCH',
            'BATCH_SETTLEMENT',
            'MISSING_IN_BANK',
            'MISSING_IN_INTERNAL',
            'BANK_SERVICE_CHARGE',
            'REFUND_MATCH',
            'UNEXPECTED_BANK_DEBIT',
            'REFUND_PENDING_BANK',
            'INTERNAL_DUPLICATE_DETECTED',
            'BANK_DUPLICATE_DETECTED',
            'IGNORED_FAILED_STATUS'
        )),
    rule_code VARCHAR(80),
    explanation TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_reconciliation_results_run_type
    ON reconciliation_results(run_id, result_type);

CREATE TABLE reconciliation_result_bank_rows (
    reconciliation_result_id BIGINT NOT NULL
        REFERENCES reconciliation_results(id) ON DELETE CASCADE,
    bank_statement_row_id BIGINT NOT NULL
        REFERENCES bank_statement_rows(id) ON DELETE RESTRICT,
    PRIMARY KEY (reconciliation_result_id, bank_statement_row_id)
);

CREATE INDEX idx_result_bank_rows_bank_row
    ON reconciliation_result_bank_rows(bank_statement_row_id);

CREATE TABLE reconciliation_result_internal_transactions (
    reconciliation_result_id BIGINT NOT NULL
        REFERENCES reconciliation_results(id) ON DELETE CASCADE,
    internal_transaction_id BIGINT NOT NULL
        REFERENCES internal_transactions(id) ON DELETE RESTRICT,
    PRIMARY KEY (
        reconciliation_result_id,
        internal_transaction_id
    )
);

CREATE INDEX idx_result_internal_transactions_transaction
    ON reconciliation_result_internal_transactions(internal_transaction_id);