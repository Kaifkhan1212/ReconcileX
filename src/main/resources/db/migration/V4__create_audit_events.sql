-- V4: Audit events table (append-only, plain BIGINT run_id, no FK)
-- run_id is a plain BIGINT with NO foreign key intentionally:
-- a FK with ON DELETE SET NULL would trigger an UPDATE which the
-- append-only trigger below would reject, causing data loss on cleanup.

CREATE TABLE audit_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id       BIGINT,                          -- nullable, no FK
    event_type   VARCHAR(60) NOT NULL,
    actor        VARCHAR(120) NOT NULL DEFAULT 'system',
    details      JSONB,
    occurred_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_audit_events_run_id
    ON audit_events(run_id);

CREATE INDEX idx_audit_events_event_type
    ON audit_events(event_type);

CREATE INDEX idx_audit_events_occurred_at
    ON audit_events(occurred_at DESC);

-- Append-only enforcement: reject UPDATE and DELETE on audit_events
CREATE OR REPLACE FUNCTION audit_events_immutable()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'audit_events rows are immutable: % on audit_events is not allowed',
        TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_events_immutable
BEFORE UPDATE OR DELETE ON audit_events
FOR EACH ROW EXECUTE FUNCTION audit_events_immutable();

-- Composite index to speed up the filtered list endpoint
CREATE INDEX idx_audit_events_run_type
    ON audit_events(run_id, event_type);

-- Ensure index exists on reconciliation_results(run_id, result_type)
CREATE INDEX IF NOT EXISTS idx_reconciliation_results_run_type
    ON reconciliation_results(run_id, result_type);
