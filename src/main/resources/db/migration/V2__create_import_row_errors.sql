CREATE TABLE import_row_errors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_import_id BIGINT NOT NULL
        REFERENCES file_imports(id) ON DELETE CASCADE,
    row_number INTEGER NOT NULL CHECK (row_number > 0),
    field_name VARCHAR(100) NOT NULL,
    error_message TEXT NOT NULL,
    raw_value TEXT
);

CREATE INDEX idx_import_row_errors_file_import_id
    ON import_row_errors(file_import_id);

ALTER TABLE file_imports
    ADD COLUMN skipped_rows INTEGER NOT NULL DEFAULT 0 CHECK (skipped_rows >= 0);
